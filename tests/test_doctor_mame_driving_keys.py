def test_not_two_jobs(tmp_path):
    """Key combinations, NOT terms and two fields of one type are left alone."""
    ports = [_port("P1_PEDAL", ":AN1", increment="KEYCODE_A"),
             _port("P1_BUTTON1", ":IN0", "1", standard="KEYCODE_LSHIFT KEYCODE_A"),
             _port("P1_BUTTON2", ":IN0", "2", standard="KEYCODE_A NOT KEYCODE_LSHIFT"),
             _port("P1_BUTTON3", ":IN0", "4", standard="KEYCODE_C"),
             _port("P1_BUTTON3", ":IN1", "4", standard="KEYCODE_C")]
    found = MamePedalKeys(_mame(tmp_path / "MAME", {"chasehq": ports}), "mame64.exe").game("chasehq")
    assert found.two_jobs == []


def test_dip_switches_are_not_inputs(tmp_path):
    """A "Gear shift" dip switch has no key sequence and never counts."""
    cfg = _cfg("dblaxle", [
        '<port tag=":DSW" type="DIPSWITCH" mask="4" defvalue="4" value="0" />\n',
        _port("P1_PEDAL", ":AN1", increment="KEYCODE_A"),
        _port("P1_BUTTON1", ":IN0", standard="KEYCODE_F")])
    folder = _mame(tmp_path / "MAME")
    _write(folder / "cfg" / "dblaxle.cfg", cfg)
    found = MamePedalKeys(folder, "mame64.exe").game("dblaxle")
    assert found.pedals == ["P1_PEDAL"]
    assert (found.no_key, found.two_jobs, found.as_folder) == ([], [], set())


