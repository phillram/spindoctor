def test_doctor_runs_the_check_after_mame_key_maps(tmp_path):
    cfg, folder = _cabinet(tmp_path)
    _mame(folder, {"coolridr": BRAKE_GONE}, PANEL_DEFAULTS)
    checks = health.run_health_checks(cfg, fix=False).checks
    names = [c.name for c in checks]
    assert names.index("MAME driving keys") == names.index("MAME key maps") + 1
    assert checks[names.index("MAME driving keys")].status == WARN
