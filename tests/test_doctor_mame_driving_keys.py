def test_check_warns_per_mame_folder(tmp_path):
    cfg, folder = _cabinet(tmp_path)
    _mame(folder, {"coolridr": BRAKE_GONE, "drivedge": CLUTCH_AND_TURBO}, PANEL_DEFAULTS)
    chk = health.check_mame_driving_keys(cfg)
    assert chk.status == WARN
    assert chk.detail == "2 of 2 MAME games with pedals have a pedal no key presses, or a key with two jobs"
    node = chk.children[0]
    assert (node.name, node.detail) == (MAME, "2 games with pedals on Driving Games")
    pedals, keys = node.children
    assert pedals.status == WARN and "coolridr (P1 Pedal 2: NONE)" in pedals.detail
    assert "cfg\\<game>.cfg" in pedals.fix
    assert keys.status == WARN and "drivedge (E: P1 Pedal 3 and P1 Button 2)" in keys.detail


def test_check_ok_when_every_pedal_has_a_key(tmp_path):
    cfg, folder = _cabinet(tmp_path)
    _mame(folder, {"coolridr": [_port("P1_PEDAL2", ":AN2", increment="KEYCODE_B")]}, PANEL_DEFAULTS)
