def test_players_past_four_have_no_built_in_key(tmp_path):
    reader = MamePedalKeys(_mame(tmp_path / "MAME"), "mame64.exe")
    assert reader.folder_binding("P4_PEDAL3").has_key
    assert not reader.folder_binding("P5_PEDAL").has_key
    assert reader.folder_binding("P5_PEDAL").why() == "joystick only"


def test_ctrlr_defaults_below_default_cfg(tmp_path):
    folder = _mame(tmp_path / "MAME", {"coolridr": BRAKE_GONE},
                   {"P1_PEDAL": {"increment": "KEYCODE_A"}},
                   ini="cfg_directory             cfg\nctrlr                     panel\n")
    _write(folder / "ctrlr" / "panel.cfg", _default({"P1_PEDAL": {"increment": "NONE"},
                                                     "P1_PEDAL2": {"increment": "NONE"}}))
    reader = MamePedalKeys(folder, "mame64.exe")
    assert reader.folder_binding("P1_PEDAL").seq == "KEYCODE_A"          # default.cfg wins
    assert reader.folder_binding("P1_PEDAL2").source == "ctrlr\\panel.cfg"
    assert reader.game("coolridr").no_key == []                          # the folder has none either


