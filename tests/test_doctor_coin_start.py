# ── which games are reported ────────────────────────────────────────────────

@pytest.mark.parametrize("default, own, reported", [
    (None, "JOYCODE_1_BUTTON9", True),                    # took MAME's key away
    ({"COIN1": "KEYCODE_S"}, "JOYCODE_1_BUTTON9", True),  # took the panel's key away
    ({"COIN1": "JOYCODE_1_BUTTON9"}, "JOYCODE_1_BUTTON8", False),  # joystick-encoder panel
    ({"COIN1": "JOYCODE_1_BUTTON9"}, "JOYCODE_1_UNKNOWN_SWITCH", True),  # device gone
    (None, "KEYCODE_S OR JOYCODE_1_BUTTON9", False),
])
def test_check_game(tmp_path, default, own, reported):
    folder = _mame(tmp_path / "MAME", default=default, games={"outrun": {"COIN1": own}})
    finding = check_game(MameInputs(folder, "mame64.exe"), "outrun")
    assert (finding is not None) == reported
    if reported:
        assert list(finding.bindings) == ["COIN1"]


def test_finding_text(tmp_path):
    folder = _mame(tmp_path / "MAME", games={
        "outrun": {"START1": "JOYCODE_1_UNKNOWN_SWITCH", "COIN1": "JOYCODE_1_UNKNOWN_SWITCH"}})
    finding = check_game(MameInputs(folder, "mame64.exe"), "outrun")
    assert finding.text() == "outrun (Coin and Start: a device MAME no longer finds)"


def test_supermodel_sections(tmp_path):
    folder = _supermodel(tmp_path / "Supermodel", (
        "[ Global ]\n; comment\nInputCoin1 = \"KEY_S,JOY1_BUTTON7\"\n\n"
        "[ srally2 ]\nInputCoin1 = \"JOY1_BUTTON9\"\nInputStart1 = \"KEY_R\"\n"))
    inputs = SupermodelInputs(folder)
    assert inputs.folder_binding("COIN1").has_key
    assert inputs.folder_binding("START1") is BUILT_IN
    assert inputs.game_binding("SRally2", "COIN1").source == "Config\\Supermodel.ini [ SRally2 ]"
    assert inputs.game_binding("scud", "COIN1") is None
    finding = check_game(inputs, "srally2")
    assert list(finding.bindings) == ["COIN1"]
    assert SupermodelInputs(tmp_path / "nowhere").folder_binding("COIN1") is BUILT_IN


# ── doctor ──────────────────────────────────────────────────────────────────

def _node(result, name):
    return next(c for c in result.children if c.name == name)


def test_doctor_is_ok_when_every_game_has_a_key(tmp_path):
    cfg, emus = _cabinet(tmp_path)
    _mame(emus / MAME, default={"COIN1": "KEYCODE_S", "START1": "KEYCODE_R"},
          games={"outrun": {"COIN1": "KEYCODE_S OR JOYCODE_1_BUTTON9"}})
    result = health.check_coin_start(cfg)
    assert result.status == OK
    assert result.children == []
    assert result.detail == "2 MAME / Supermodel games: each can take a coin and start from a key"


def test_doctor_warns_for_games_whose_own_binding_has_no_key(tmp_path):
    games = [f"game{i}" for i in range(7)] + ["outrun"]
    cfg, emus = _cabinet(tmp_path, wheels={"Driving Games": games + ["fine"]})
    own = {g: {"COIN1": "JOYCODE_1_BUTTON9", "START1": "JOYCODE_1_BUTTON10"} for g in games}
    own["outrun"] = {"COIN1": "JOYCODE_1_UNKNOWN_SWITCH"}
    _mame(emus / MAME, games=own)
    result = health.check_coin_start(cfg)
    assert result.status == WARN
    assert result.detail == "8 of 9 MAME / Supermodel games can't take a coin or start from a key"
    node = _node(result, MAME)
    assert node.detail == "9 games on Driving Games"
    games_node = _node(node, "games")
    assert games_node.status == WARN
    assert games_node.detail.startswith(
        "8 of 9 games have a Coin or Start binding of their own that no key can press: "
        "outrun (Coin: a device MAME no longer finds), game0 (Coin and Start: joystick only), ")
    assert games_node.detail.endswith(", and 3 more")
    assert "cfg\\<game>.cfg" in games_node.fix and "MAME closed" in games_node.fix


def test_doctor_joystick_encoder_panel_is_info(tmp_path):
    cfg, emus = _cabinet(tmp_path)
    _mame(emus / MAME, default={"COIN1": "JOYCODE_1_BUTTON9"},
          games={"outrun": {"COIN1": "JOYCODE_1_BUTTON8"}})
    result = health.check_coin_start(cfg)
    assert result.status == INFO
    wide = _node(_node(result, MAME), "cfg\\default.cfg")
    assert wide.status == INFO
    assert wide.detail == ("Coin has no key (joystick only: JOYCODE_1_BUTTON9): fine for a "
                           "joystick-encoder panel, but a keyboard panel can't use Coin in 1 game")
    assert result.detail.endswith("(fine for a joystick-encoder panel)")


def test_doctor_lost_device_in_default_cfg_warns(tmp_path):
    cfg, emus = _cabinet(tmp_path, wheels={"Driving Games": ["outrun", "chasehq", "turbo"]})
    _mame(emus / MAME, default={"START1": "JOYCODE_1_UNKNOWN_SWITCH"},
          games={"turbo": {"START1": "KEYCODE_1"}})
    result = health.check_coin_start(cfg)
    wide = _node(_node(result, MAME), "cfg\\default.cfg")
    assert wide.status == WARN
    assert wide.detail.endswith("so 2 games without a binding of their own can't start from any button")
    assert result.detail == "2 of 3 MAME / Supermodel games can't take a coin or start from a key"


def test_doctor_skips_hidden_wheels_and_mess_consoles(tmp_path):
    cfg, emus = _cabinet(tmp_path, wheels={"Gun Games": ["area51"], "Colecovision": ["dkong"]},
                         hidden=("Gun Games",))
    _mame(emus / MAME, games={"area51": {"COIN1": "GUNCODE_1_BUTTON2"},
                              "dkong": {"COIN1": "JOYCODE_1_BUTTON9"}})
    result = health.check_coin_start(cfg)
    assert (result.status, result.detail) == (OK, "no MAME or Supermodel games on the Main Menu's wheels")


def test_doctor_follows_games_ini_overrides(tmp_path):
    cfg, emus = _cabinet(
        tmp_path, wheels={"Driving Games": ["outrun", "daytona", "srally2"], "Sega Model 3": []},
        emulators={"Driving Games": "Model 2", "Sega Model 3": "SuperModel"},
        games_ini={"Driving Games": f"[outrun]\nEmulator={MAME}\n\n[srally2]\nSystem=Sega Model 3\n"})
    _mame(emus / MAME, games={"outrun": {"COIN1": "JOYCODE_1_BUTTON9"}})
    _supermodel(emus / "Supermodel", "[ Global ]\nInputCoin1 = \"KEY_S\"\n"
                                     "[ srally2 ]\nInputStart1 = \"JOY1_BUTTON10\"\n")
    result = health.check_coin_start(cfg)
    assert result.detail == "2 of 2 MAME / Supermodel games can't take a coin or start from a key"
    assert _node(_node(result, MAME), "games").detail.endswith(": outrun (Coin: joystick only)")
    supermodel = _node(_node(result, "SuperModel"), "games")
    assert supermodel.detail.endswith(": srally2 (Start: joystick only)")
    assert "Config\\Supermodel.ini" in supermodel.fix


