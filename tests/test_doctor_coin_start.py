def test_mame_built_in_keys_when_nothing_is_set(tmp_path):
    inputs = MameInputs(_mame(tmp_path / "MAME"), "mame64.exe")
    assert inputs.folder_binding("COIN1") is BUILT_IN
    assert inputs.game_binding("outrun", "START1") is None


def test_mame_layers_in_order(tmp_path):
    """Built in < ctrlr default < default.cfg < ctrlr game section < cfg\\<game>.cfg."""
    folder = _mame(tmp_path / "MAME", ini="ctrlr                     arcade\n",
                   default={"START1": "KEYCODE_R"},
                   games={"outrun": {"COIN1": "JOYCODE_1_BUTTON9"}})
    _write(folder / "ctrlr" / "arcade.cfg", (
        '<?xml version="1.0"?>\n<mameconfig version="10">\n'
        '  <system name="default"><input>\n'
        '    <port type="COIN1"><newseq type="standard">KEYCODE_S</newseq></port>\n'
        '    <port type="START1"><newseq type="standard">KEYCODE_1</newseq></port>\n'
        '  </input></system>\n'
        '  <system name="chasehq"><input>\n'
        '    <port tag=":IN" type="START1" mask="1" defvalue="1">'
        '<newseq type="standard">JOYCODE_1_BUTTON10</newseq></port>\n'
        '  </input></system>\n</mameconfig>\n'))
    inputs = MameInputs(folder, "mame64.exe")
    assert inputs.folder_binding("START1").seq == "KEYCODE_R"            # default.cfg wins
    assert inputs.folder_binding("START1").source == "cfg\\default.cfg"
    assert inputs.folder_binding("COIN1").seq == "KEYCODE_S"             # from the ctrlr file
    assert inputs.folder_binding("COIN1").source == "ctrlr\\arcade.cfg"
    assert inputs.game_binding("outrun", "COIN1").seq == "JOYCODE_1_BUTTON9"
    assert inputs.game_binding("outrun", "COIN1").source == "cfg\\outrun.cfg"
    assert inputs.game_binding("outrun", "START1") is None
    assert inputs.game_binding("chasehq", "START1").source == "ctrlr\\arcade.cfg"


def test_mame_reads_cfg_directory_and_any_case(tmp_path):
    folder = _mame(tmp_path / "MAME", ini="cfg_directory             \"settings\"\n")
    _write(folder / "settings" / "OutRun.cfg", _cfg_xml("outrun", {"COIN1": "JOYCODE_1_BUTTON9"}))
    inputs = inputs_for(folder, "MAME64.EXE")
    assert isinstance(inputs, MameInputs)
    assert inputs.game_binding("outrun", "COIN1").source == "settings\\OutRun.cfg"


def test_mame_ini_with_windows_line_ends(tmp_path):
    folder = _mame(tmp_path / "MAME")
    (folder / "mame.ini").write_bytes(b"cfg_directory             settings\r\nctrlr     \r\n")
    _write(folder / "settings" / "outrun.cfg", _cfg_xml("outrun", {"COIN1": "JOYCODE_1_BUTTON9"}))
    assert MameInputs(folder, "mame64.exe").game_binding("outrun", "COIN1") is not None


def test_mame_ignores_other_systems_and_broken_files(tmp_path):
    folder = _mame(tmp_path / "MAME", games={"outrun": {"COIN1": "JOYCODE_1_BUTTON9"}})
