"""Tests for the `doctor` Coin/Start check.

A game set up for a steering wheel, pad or gun can bind Coin 1 or 1 Player
Start to that device's buttons only, in its own MAME cfg or Supermodel
section.  On a keyboard-encoder panel it then boots, but nothing inserts a
coin or starts it; MAME also saves ``JOYCODE_n_UNKNOWN_*`` once the device is
unplugged.  Each test builds a small cabinet in a temp dir.
"""
from __future__ import annotations

import pytest

from spindoctor import health
from spindoctor.coin_start import (
    BUILT_IN,
    MameInputs,
    SupermodelInputs,
    check_game,
    inputs_for,
    mame_binding,
    supermodel_binding,
)
from spindoctor.config import Config

OK = health.Status.OK
WARN = health.Status.WARN
INFO = health.Status.INFO
MAME = "MAME (Driving Games)"


def _write(path, text=""):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _cfg_xml(system, ports):
    """A MAME cfg whose <system name=*system*> sets *ports* (type -> sequence)."""
    body = "".join(
        f'            <port tag=":IN" type="{t}" mask="1" defvalue="1">\n'
        f'                <newseq type="standard">\n                    {seq}\n'
        "                </newseq>\n            </port>\n"
        for t, seq in ports.items()
    )
    return ('<?xml version="1.0"?>\n<!-- This file is autogenerated -->\n'
            f'<mameconfig version="10">\n    <system name="{system}">\n        <input>\n'
            f"{body}        </input>\n    </system>\n</mameconfig>\n")


def _mame(folder, games=None, default=None, ini="", exe="mame64.exe"):
    """A MAME folder: ``cfg\\<game>.cfg`` per *games* entry, ``cfg\\default.cfg``."""
    (folder / "cfg").mkdir(parents=True, exist_ok=True)
    _write(folder / exe)
    _write(folder / "mame.ini", ini or "cfg_directory             cfg\nctrlr                     \n")
    for game, ports in (games or {}).items():
        _write(folder / "cfg" / f"{game}.cfg", _cfg_xml(game, ports))
    if default is not None:
        _write(folder / "cfg" / "default.cfg", _cfg_xml("default", default))
    return folder


def _cabinet(tmp_path, wheels=None, hidden=(), emulators=None, games_ini=None):
    """HyperSpin + RocketLauncher dirs.  *wheels* maps wheel name -> DB game
    names, *emulators* wheel name -> Default_Emulator (MAME (Driving Games)),
    *games_ini* wheel name -> its Games.ini text."""
    wheels = {"Driving Games": ["outrun", "chasehq"]} if wheels is None else wheels
    emulators = emulators or {}
    hs, rl = tmp_path / "HyperSpin", tmp_path / "RocketLauncher"
    menu = "".join(f'<game name="{w}" enabled="False"/>' if w in hidden else f'<game name="{w}"/>'
                   for w in wheels)
    _write(hs / "Databases" / "Main Menu" / "Main Menu.xml", f"<menu>{menu}</menu>")
    for wheel, games in wheels.items():
        xml = "".join(f'<game name="{g}"/>' for g in games)
        _write(hs / "Databases" / wheel / f"{wheel}.xml", f"<menu>{xml}</menu>")
        _write(rl / "Settings" / wheel / "Emulators.ini",
               f"[ROMS]\nDefault_Emulator={emulators.get(wheel, MAME)}\nRom_Path=E:\\Games\n")
    for wheel, text in (games_ini or {}).items():
        _write(rl / "Settings" / wheel / "Games.ini", text)
    _write(rl / "Settings" / "Global Emulators.ini",
           f"[{MAME}]\nEmu_Path=..\\Emulators\\{MAME}\\mame64.exe\nRom_Extension=zip\n\n"
           "[SuperModel]\nEmu_Path=..\\Emulators\\Supermodel\\Supermodel.exe\nRom_Extension=zip\n\n"
           "[Model 2]\nEmu_Path=..\\Emulators\\Model 2\\emulator_multicpu.exe\nRom_Extension=zip\n")
    cfg = Config(roms_dir=str(tmp_path / "Games"), hyperspin_dir=str(hs),
                 rocketlauncher_dir=str(rl), emulators_dir=str(tmp_path / "Emulators"))
    return cfg, tmp_path / "Emulators"


def _supermodel(folder, text):
    _write(folder / "Supermodel.exe")
    _write(folder / "Config" / "Supermodel.ini", text)
    return folder


# ── bindings ────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("seq, has_key, lost, why", [
    ("KEYCODE_5", True, False, "nothing"),
    ("KEYCODE_S OR JOYCODE_1_BUTTON9", True, False, "joystick only"),
    ("KEYCODE_LSHIFT KEYCODE_1", True, False, "nothing"),
    ("KEYCODE_5 NOT KEYCODE_LALT", True, False, "nothing"),
    ("JOYCODE_1_BUTTON9", False, False, "joystick only"),
    ("NOT KEYCODE_LALT JOYCODE_1_BUTTON1", False, False, "joystick only"),
    ("JOYCODE_1_UNKNOWN_SWITCH", False, True, "a device MAME no longer finds"),
    ("JOYCODE_2_BUTTON3 OR JOYCODE_1_UNKNOWN_SWITCH", False, True, "a device MAME no longer finds"),
    ("MOUSECODE_1_BUTTON1 OR GUNCODE_1_BUTTON1", False, False, "mouse or light gun only"),
    ("NONE", False, False, "nothing"),
])
def test_mame_binding(seq, has_key, lost, why):
    b = mame_binding(f"\n   {seq}\n  ", "cfg\\x.cfg")
    assert (b.seq, b.has_key, b.lost, b.why()) == (seq, has_key, lost, why)


@pytest.mark.parametrize("value, has_key, why", [
    ('"KEY_S,JOY1_BUTTON7,JOY1_BUTTON9"', True, "joystick only"),
    ('"KEY_LEFTSHIFT+KEY_1"', True, "nothing"),
    ('"JOY1_BUTTON9"', False, "joystick only"),
    ('"!KEY_A+JOY1_BUTTON1"', False, "joystick only"),
    ('"MOUSE_LEFT_BUTTON"', False, "mouse only"),
    ('"NONE"', False, "nothing"),
])
def test_supermodel_binding(value, has_key, why):
    b = supermodel_binding(value, "Config\\Supermodel.ini [ Global ]")
    assert (b.has_key, b.lost, b.why()) == (has_key, False, why)


