"""Tests for the `doctor` **Emulator ROM folders** check
(``health.check_emulator_rom_paths``).

Some emulators keep a ROM or save folder in their own config file, which
neither ``generate-config`` nor ``migrate`` rewrites after a ROM-drive move.
The fixtures copy the real files' formats.  "Stale" folders are absolute
paths under ``tmp_path`` that were never created, so the tests behave the
same on Windows and POSIX.
"""
from __future__ import annotations

import os

from spindoctor import health
from spindoctor.config import Config


def _cabinet(tmp_path):
    """RocketLauncher, Emulators and ROM folders with no emulator installed."""
    rl = tmp_path / "RocketLauncher"
    (rl / "Settings").mkdir(parents=True)
    emus = tmp_path / "Emulators"
    emus.mkdir()
    roms = tmp_path / "roms"
    roms.mkdir()
    cfg = Config(roms_dir=str(roms), rocketlauncher_dir=str(rl), emulators_dir=str(emus))
    return cfg, rl, emus, roms


def _register(rl, section, emu_path, module=None):
    """Add an emulator entry to RocketLauncher's Global Emulators.ini."""
    ini = rl / "Settings" / "Global Emulators.ini"
    text = ini.read_text(encoding="utf-8") if ini.exists() else "\n"
    ini.write_text(text + f"[{section}]\nEmu_Path={emu_path}\nModule={module or section + '.ahk'}\n",
                   encoding="utf-8")


def _write(path, text, encoding="utf-8"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding=encoding)
    return path


def _node(result, path):
    """The row for config file *path*."""
    return next(c for c in result.children if c.name.endswith(str(path)))


def _sub(node, name):
    return next(c for c in node.children if c.name == name)


def test_aae_stale_rom_path_warns_and_comment_line_is_skipped(tmp_path):
    cfg, rl, emus, _roms = _cabinet(tmp_path)
    stale = tmp_path / "J" / "Games" / "AAE"
    _register(rl, "AAE", "..\\Emulators\\AAE\\aae.exe")
    ini = _write(emus / "AAE" / "aae.ini",
                 ";####AAE MAIN INI####\n\n[main]\n\n"
                 "#mame_rom_path = c:\\mame\\roms\n"
                 "doublebuffer = 1               ;Enable Duble buffering\n"
                 f"mame_rom_path={stale}\n"
                 "[]\nmain=1\n")

    result = health.check_emulator_rom_paths(cfg)
    assert result.status == health.Status.WARN
    node = _node(result, ini)
    assert node.name == f"AAE: {ini}"
    assert node.detail == "1 of 1 folder path(s) not found"  # the # line isn't a setting
    row = _sub(node, "mame_rom_path")
    assert row.status == health.Status.WARN
    assert row.detail == f"folder not found: {stale}"
    assert row.fix.startswith(f"In {ini}, ")


def test_demul_bom_one_stale_roms_entry_one_ok(tmp_path):
    cfg, rl, emus, _roms = _cabinet(tmp_path)
    ok = tmp_path / "E" / "Games" / "Sammy Atomiswave"
    ok.mkdir(parents=True)
    stale = tmp_path / "D" / "Arcade" / "Games" / "Sega Naomi"
    _register(rl, "Demul57", "..\\Emulators\\demul32-0.5.7\\demul.exe")
    # [files] first, so an unstripped BOM would hide its section header.
    ini = _write(emus / "demul32-0.5.7" / "Demul.ini",
                 "[files]\n"
                 f"roms0 = {ok}{os.sep}\n"
                 f"roms1 = {stale}{os.sep}\n"
                 "romsPathsCount = 2\n"
                 f"roms2 = {tmp_path / 'unused'}{os.sep}\n"  # past romsPathsCount: Demul ignores it
                 "\n[main]\nregion = 1\n"
                 "[main]\nnaomiBiosAuto=true\n",  # Demul writes [main] twice
                 encoding="utf-8-sig")
    assert ini.read_bytes().startswith(b"\xef\xbb\xbf")

    node = _node(health.check_emulator_rom_paths(cfg), ini)
    assert node.name == f"Demul: {ini}"
    assert node.status == health.Status.WARN
    assert node.detail == "1 of 2 folder path(s) not found"
    assert [c.name for c in node.children] == ["roms1"]
    assert node.children[0].detail == f"folder not found: {stale}{os.sep}"


