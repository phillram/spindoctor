def test_fix_suggests_same_folder_under_roms_dir(tmp_path):
    cfg, rl, emus, roms = _cabinet(tmp_path)
    (roms / "Sega Naomi").mkdir()
    (roms / "Nintendo Pokemon Mini").mkdir()
    old = tmp_path / "D" / "Arcade" / "Games"
    _register(rl, "Demul", "..\\Emulators\\Demul\\demul.exe")
    demul = _write(emus / "Demul" / "Demul.ini",
                   "[files]\n"
                   f"roms0 = {old / 'Sega Naomi'}{os.sep}\n"
                   f"roms1 = {old / 'Sega Dreamcast'}{os.sep}\n"
                   "romsPathsCount = 2\n")
    _register(rl, "PokeMini", "..\\Emulators\\PokeMini\\PokeMini.exe")
    poke = _write(emus / "PokeMini" / "pokemini.cfg",
                  f"eepromfile={old / 'Nintendo Pokemon Mini' / 'Game.min.eep'}\n")

    result = health.check_emulator_rom_paths(cfg)
    naomi = _sub(_node(result, demul), "roms0")
    assert naomi.fix == f"In {demul}, set roms0={roms / 'Sega Naomi'}{os.sep}"
    eep = _sub(_node(result, poke), "eepromfile")
    assert eep.fix == f"In {poke}, set eepromfile={roms / 'Nintendo Pokemon Mini' / 'Game.min.eep'}"
    # Nothing to rebase onto: a generic hint, never a made-up path.
    dreamcast = _sub(_node(result, demul), "roms1")
    assert dreamcast.fix == f"In {demul}, point roms1 at the folder's new location"


def test_ok_when_every_folder_exists(tmp_path):
    cfg, rl, emus, roms = _cabinet(tmp_path)
    (roms / "AAE").mkdir()
    (emus / "Demul" / "roms").mkdir(parents=True)
    _register(rl, "AAE", "..\\Emulators\\AAE\\aae.exe")
    _register(rl, "Demul", "..\\Emulators\\Demul\\demul.exe")
    _write(emus / "AAE" / "aae.ini", f"[main]\nmame_rom_path={roms / 'AAE'}\n")
    # A relative value resolves from the emulator's folder.
    _write(emus / "Demul" / "Demul.ini", "[files]\nroms0 = roms\\\nromsPathsCount = 1\n")

    result = health.check_emulator_rom_paths(cfg)
    assert result.status == health.Status.OK
    assert [c.detail for c in result.children] == ["1 folder path(s) OK", "1 folder path(s) OK"]


def test_global_emulators_entry_wins_over_emulators_dir_scan(tmp_path):
    cfg, rl, emus, _roms = _cabinet(tmp_path)
    live = tmp_path / "E" / "Games" / "Sega Naomi"
    live.mkdir(parents=True)
    _register(rl, "Demul", "..\\Emulators\\Demul\\demul.exe")
    _write(emus / "Demul" / "Demul.ini", f"[files]\nroms0 = {live}\nromsPathsCount = 1\n")
    # A leftover copy RocketLauncher never launches is not reported.
    _write(emus / "Demul (backup)" / "Demul.ini",
           f"[files]\nroms0 = {tmp_path / 'J' / 'Games' / 'Sega Naomi'}\nromsPathsCount = 1\n")

    result = health.check_emulator_rom_paths(cfg)
    assert result.status == health.Status.OK
    assert len(result.children) == 1
    assert "Demul (backup)" not in result.children[0].name


def test_info_not_warn_when_the_rocketlauncher_module_sets_the_folder(tmp_path):
    cfg, rl, emus, _roms = _cabinet(tmp_path)
    stale = tmp_path / "D" / "Arcade" / "Games" / "Sega Naomi"
    modules = rl / "Modules" / "Demul"
    # v0.7-style module: adds RocketLauncher's ROM folder to Demul.ini itself.
    _write(modules / "Demul (v0.7).ahk",
           'romPathCount := DemuleIni.Read("files", "romsPathsCount")\n'
           'DemuleIni.Write(nextPath, "files", "romsPathsCount")\n')
    # v0.5.7-style module: only passes -rom=, so Demul searches roms0..N.
    _write(modules / "Demul (v0.5.7).ahk",
           '; Demul.ini romsPathsCount must list your rom folders\n'
           'romCLI := "-rom=" . romName\n')
    _register(rl, "Demul", "..\\Emulators\\Demul\\demul.exe", module="Demul (v0.7).ahk")
    _register(rl, "Demul57", "..\\Emulators\\demul32-0.5.7\\demul.exe",
              module="..\\Demul\\Demul (v0.5.7).ahk")
    body = f"[files]\nroms0 = {stale}{os.sep}\nromsPathsCount = 1\n"
    v07 = _write(emus / "Demul" / "Demul.ini", body)
    v057 = _write(emus / "demul32-0.5.7" / "Demul.ini", body)

    result = health.check_emulator_rom_paths(cfg)
    harmless = _node(result, v07)
    assert harmless.status == health.Status.INFO
    assert harmless.detail == "roms0 not found; harmless, Demul (v0.7).ahk sets the folder at launch"
    assert _node(result, v057).status == health.Status.WARN
    assert result.status == health.Status.WARN


def test_warn_when_any_module_launching_the_folder_leaves_it_alone(tmp_path):
    cfg, rl, emus, _roms = _cabinet(tmp_path)
    _write(rl / "Modules" / "AAE" / "AAE.ahk",
           'aaeINI.Write(romPath, "main", "mame_rom_path")\t; always correct\n')
    # A commented-out write doesn't count.
    _write(rl / "Modules" / "AAE (Old)" / "AAE (Old).ahk",
           ';aaeINI.Write(romPath, "main", "mame_rom_path")\n')
    _register(rl, "AAE", "..\\Emulators\\AAE\\aae.exe")
    _register(rl, "AAE (Old)", "..\\Emulators\\AAE\\aae.exe")
    _write(emus / "AAE" / "aae.ini", f"[main]\nmame_rom_path={tmp_path / 'J' / 'Games' / 'AAE'}\n")

    result = health.check_emulator_rom_paths(cfg)
    assert len(result.children) == 1  # one folder, two RocketLauncher entries
    assert result.children[0].status == health.Status.WARN


