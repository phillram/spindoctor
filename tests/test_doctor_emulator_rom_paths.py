def test_windows_drive_paths_are_only_checked_on_windows():
    folder = health._setting_folder("J:\\Games\\Nintendo Pokemon Mini\\Game.min.eep", None, True)
    if os.name == "nt":
        assert str(folder) == "J:\\Games\\Nintendo Pokemon Mini"
    else:
        assert folder is None  # can't be checked from a POSIX dev machine


