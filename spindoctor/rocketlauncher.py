def guess_emulator(system_name: str) -> str:
    ovr = get_system_overrides().get(system_name, {})
    if isinstance(ovr.get("emulator"), str) and ovr["emulator"]:
        return ovr["emulator"]
    return EMULATOR_MAP.get(system_name.lower(), "RetroArch")


